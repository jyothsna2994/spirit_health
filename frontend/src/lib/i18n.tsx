const dict: Record<Lang, Partial<Record<Key, string>>> = { en, hi, te, ta };
const LANG_KEY = "spirit_health_lang";

type I18n = {
  lang: Lang;
  setLang: (lang: Lang) => void;
  t: (key: Key, vars?: Record<string, string | number>) => string;
  speech: string;
  locale: string;
};

const Ctx = createContext<I18n>({
  lang: "en",
  setLang: () => {},
  t: (key) => en[key],
  speech: "en-IN",
  locale: "en-IN",
});

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>("en");

  useEffect(() => {
    AsyncStorage.getItem(LANG_KEY)
      .then((saved) => {
        if (saved && saved in dict) setLangState(saved as Lang);
      })
      .catch(() => {});
  }, []);

  const setLang = useCallback((next: Lang) => {
    setLangState(next);
    AsyncStorage.setItem(LANG_KEY, next).catch(() => {});
    /* Remember it on the account too (best effort - the app works without it). */
    getSession().then((s) => {
      if (s) api.patch("/api/me", { preferredLanguage: next }).catch(() => {});
    });
  }, []);

  const value = useMemo<I18n>(() => {
    const meta = LANGS.find((l) => l.code === lang)!;
    return {
      lang,
      setLang,
      speech: meta.speech,
      locale: meta.locale,
      t: (key, vars) => {
        let text = dict[lang][key] ?? en[key] ?? key;
        if (vars) for (const [k, v] of Object.entries(vars)) text = text.replace(`{${k}}`, String(v));
        return text;
      },
    };
  }, [lang, setLang]);

  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export const useI18n = () => useContext(Ctx);
